// Regenerates src/content/stats.generated.ts (challenge count and slug/title/difficulty index per topic).
import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { topicStats as previous } from "../src/content/stats.generated.ts";
import type { ChallengeMeta, Topic } from "../src/content/types.ts";

const contentDir = resolve(import.meta.dirname, "../src/content");
const courses = ["core", "intermediate", "dom", "practice", "interview"];

const stats: Record<string, { count: number; challenges: ChallengeMeta[] }> = {};
for (const course of courses) {
  const dir = join(contentDir, course);
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".ts"))
    .sort()) {
    const key = `${course}/${file.slice(0, -3)}`;
    try {
      const mod = (await import(pathToFileURL(join(dir, file)).href)) as { default: Topic };
      stats[key] = {
        count: mod.default.challenges.length,
        challenges: mod.default.challenges.map(({ slug, title, difficulty }) => ({
          slug,
          title,
          difficulty,
        })),
      };
    } catch (error) {
      // Keep the last good entry so a file that is mid-edit does not wipe its stats.
      console.warn(`Could not load ${key}.ts, keeping previous stats: ${(error as Error).message}`);
      const kept = previous[key];
      if (kept && "challenges" in kept) stats[key] = kept;
    }
  }
}

const body = Object.entries(stats)
  .map(([key, s]) => {
    const items = s.challenges.map((c) => `      ${JSON.stringify(c)},`).join("\n");
    return `  "${key}": {\n    count: ${s.count},\n    challenges: [\n${items}\n    ],\n  },`;
  })
  .join("\n");

writeFileSync(
  join(contentDir, "stats.generated.ts"),
  `// Generated by \`npm run gen:catalog\`. Do not edit by hand.
import type { ChallengeMeta } from "./types";

export const topicStats: Record<string, { count: number; challenges: ChallengeMeta[] }> = {
${body}
};
`,
);
console.log(`Wrote stats for ${Object.keys(stats).length} topics.`);
